# ===================== 函数2：卖装备（完整移植） =====================
def 卖装备():
    print("【流程】开始卖装备环节")
    # 后台按I打开背包（VK L=73对应按键I，原脚本73=I）
    key_press("L", 4000)
    rand_delay(4000)
    # 前台鼠标移动到背包按钮
    move_to(1314, 168, 1000)
    left_click(1000)

    j = 0
    while j == 0:
        rand_delay(5000)
        print("【卖装备】按下Shift")
        key_down("Shift")
        rand_delay(3000)
        # 多点找色
        x, y = find_multi_color(MULTICOLOR_X1, MULTICOLOR_Y1, MULTICOLOR_X2, MULTICOLOR_Y2, MAIN_COLOR, OFFSET_COLORS)
        if x > 0:
            print(f"【卖装备】发现10级装备 坐标({x},{y})")
            move_to(x - 10, y - 10, 3000)
            rand_delay(3000)
            key_press("L", 3000)
            rand_delay(3000)
            left_click(3000)
            rand_delay(3000)
            move_to(1372, 168, 3000)
            right_click(3000)
        else:
            print("【卖装备】未找到10级装备，退出循环")
            key_press("Y", 5000)
            rand_delay(5000)
            key_press("Enter", 3000)
            rand_delay(3000)
            key_press("Esc", 3000)
            j = 1
        key_up("Shift")
    rand_delay(5000)

